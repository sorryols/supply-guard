"""Блокові тести виправлень версії 1.0.1 (за результатами експерименту на реальних бібліотеках)."""

from packaging.version import Version

from libsentinel import dast
from libsentinel.avt_meta import _tag_version, find_tag
from libsentinel.sast import is_generated_metadata


def test_tag_version_normalization():
    assert _tag_version("2024.08.30") == Version("2024.8.30")      # certifi
    assert _tag_version("release_2024.2") == Version("2024.2")      # pytz
    assert _tag_version("v1.2.3") == Version("1.2.3")
    assert _tag_version("tqdm-4.66.5") == Version("4.66.5")
    assert _tag_version("latest") is None


class FakeGH:
    def __init__(self, tags):
        self.tags = tags

    def get(self, path, allow_404=True):
        if "/git/ref/tags/" in path:
            return {"__404__": True}
        if "/tags?" in path:
            return [{"name": t} for t in self.tags] if "page=1" in path else []
        return {"__404__": True}


def test_find_tag_zero_padded():
    gh = FakeGH(["2024.07.04", "2024.08.30"])
    assert find_tag(gh, "certifi", "python-certifi", "certifi", "2024.8.30") == "2024.08.30"


def test_find_tag_absent():
    assert find_tag(FakeGH(["v1.0.0"]), "o", "r", "pkg", "2.0.0") is None


def test_generated_version_file():
    scm = ('# file generated by setuptools-scm\n# don\'t change, don\'t track in version control\n'
           'from typing import Tuple, Union\nTYPE_CHECKING = False\nif TYPE_CHECKING:\n    VERSION_TUPLE = Tuple\n'
           '__version__ = version = "4.66.5"\n__version_tuple__ = version_tuple = (4, 66, 5)\n')
    assert is_generated_metadata(scm)
    assert is_generated_metadata('__version__ = "1.0"\n')
    assert not is_generated_metadata('import os\nos.system("id")\n')
    assert not is_generated_metadata('__version__ = __import__("os").getenv("X")\n')


def test_compiler_toolchain_not_b2(cfg):
    trace = ('1 execve("/usr/bin/x86_64-linux-gnu-gcc-12", ["gcc"], 0x0) = 0\n'
             '2 execve("/usr/lib/gcc/x86_64-linux-gnu/12/cc1", ["cc1"], 0x0) = 0\n'
             '3 execve("/usr/lib/gcc/x86_64-linux-gnu/12/collect2", ["collect2"], 0x0) = 0\n'
             '4 execve("/usr/bin/x86_64-linux-gnu-ld.bfd", ["ld"], 0x0) = 0\n'
             '5 execve("/bin/sh", ["sh", "-c", "curl x"], 0x0) = 0\n')
    info = {"home": "/home/sandbox", "venv": "/tmp/venv", "honeypots": []}
    f = dast.analyze_events(dast.parse_trace(trace, "install"), info, cfg)
    assert [n for n, _, _ in f.programs] == ["sh"]
